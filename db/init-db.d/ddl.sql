-- ### 0. CREACIÓN DEL USUARIO Y ASIGNACIÓN DE PERMISOS
-- Nota: 'IDENTIFIED BY' establece la contraseña del usuario.
CREATE USER API_USER IDENTIFIED BY tu_password_seguro;

-- Otorgar permisos básicos para que el usuario pueda conectarse y crear objetos
GRANT CONNECT, RESOURCE TO API_USER;
GRANT CREATE SESSION TO API_USER;
GRANT CREATE TABLE TO API_USER;
GRANT CREATE VIEW TO API_USER;
ALTER USER API_USER QUOTA UNLIMITED ON USERS;

-- Cambiar la sesión actual para que todos los comandos siguientes
-- se ejecuten en el esquema del nuevo usuario. ¡Esta línea es clave!
ALTER SESSION SET CURRENT_SCHEMA = API_USER;

-- ### 1. CREACIÓN DE TABLAS (SIN LLAVES FORÁNEAS)
CREATE TABLE CENTRO (
    ID_CENTRO NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL
);
ALTER TABLE CENTRO ADD CONSTRAINT CENTRO_PK PRIMARY KEY (ID_CENTRO);

CREATE TABLE CORRELATIVO (
    ID_CORRELATIVO NUMBER NOT NULL,
    FECHA DATE NOT NULL,
    NO_EXAMEN NUMBER NOT NULL
);
ALTER TABLE CORRELATIVO ADD CONSTRAINT CORRELATIVO_PK PRIMARY KEY (ID_CORRELATIVO);

CREATE TABLE DEPARTAMENTO (
    ID_DEPARTAMENTO NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    CODIGO NUMBER NOT NULL
);
ALTER TABLE DEPARTAMENTO ADD CONSTRAINT DEPARTAMENTO_PK PRIMARY KEY (ID_DEPARTAMENTO);

CREATE TABLE ESCUELA (
    ID_ESCUELA NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    DIRECCION VARCHAR2(100) NOT NULL,
    ACUERDO VARCHAR2(100) NOT NULL
);
ALTER TABLE ESCUELA ADD CONSTRAINT ESCUELA_PK PRIMARY KEY (ID_ESCUELA);

CREATE TABLE PREG (
    ID_PREG NUMBER NOT NULL,
    PREG_TEXTO VARCHAR2(500) NOT NULL,
    RES VARCHAR2(100) NOT NULL,
    RES1 VARCHAR2(500) NOT NULL,
    RES2 VARCHAR2(500) NOT NULL,
    RES3 VARCHAR2(500),
    RES4 VARCHAR2(500)
);
ALTER TABLE PREG ADD CONSTRAINT PREG_PK PRIMARY KEY (ID_PREG);

CREATE TABLE PREG_PRACT (
    ID_PREG_PRACT NUMBER NOT NULL,
    PREG_TEXTO VARCHAR2(500) NOT NULL,
    PUNTEO NUMBER NOT NULL
);
ALTER TABLE PREG_PRACT ADD CONSTRAINT PREG_PRACT_PK PRIMARY KEY (ID_PREG_PRACT);

-- ### 2. CREACIÓN DE TABLAS DEPENDIENTES
CREATE TABLE MUNICIPIO (
    ID_MUNICIPIO NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    CODIGO NUMBER NOT NULL,
    DEPARTAMENTO_ID_DEPARTAMENTO NUMBER NOT NULL
);
ALTER TABLE MUNICIPIO ADD CONSTRAINT MUNICIPIO_PK PRIMARY KEY (ID_MUNICIPIO);

CREATE TABLE UBICACION (
    ESCUELA_ID_ESCUELA NUMBER NOT NULL,
    CENTRO_ID_CENTRO NUMBER NOT NULL
);
ALTER TABLE UBICACION ADD CONSTRAINT UBICACION_PK PRIMARY KEY (ESCUELA_ID_ESCUELA, CENTRO_ID_CENTRO);

CREATE TABLE REGISTRO (
    ID_REGISTRO NUMBER NOT NULL,
    FECHA DATE NOT NULL,
    TIPO_TRAMITE VARCHAR2(100) NOT NULL,
    TIPO_LICENCIA VARCHAR2(100) NOT NULL,
    NOMBRE_COMPLETO VARCHAR2(100),
    GENERO VARCHAR2(100) NOT NULL,
    MUNICIPIO_ID_MUNICIPIO NUMBER NOT NULL,
    UBICACION_ESCUELA_ID NUMBER NOT NULL,
    UBICACION_CENTRO_ID NUMBER NOT NULL
);
ALTER TABLE REGISTRO ADD CONSTRAINT REGISTRO_PK PRIMARY KEY (ID_REGISTRO);

CREATE TABLE EXAMEN (
    ID_EXAMEN NUMBER NOT NULL,
    REGISTRO_ID_REGISTRO NUMBER NOT NULL,
    CORRELATIVO_ID_CORRELATIVO NUMBER NOT NULL
);
ALTER TABLE EXAMEN ADD CONSTRAINT EXAMEN_PK PRIMARY KEY (ID_EXAMEN);

CREATE TABLE RES_PRACT_USU (
    ID_RES_PRACT NUMBER NOT NULL,
    NOTA NUMBER NOT NULL,
    PREG_PRACT_ID_PREG_PRACT NUMBER NOT NULL,
    EXAMEN_ID_EXAMEN NUMBER NOT NULL
);
ALTER TABLE RES_PRACT_USU ADD CONSTRAINT RES_PRACT_USU_PK PRIMARY KEY (ID_RES_PRACT);

CREATE TABLE RES_USU (
    ID_RES_USU NUMBER NOT NULL,
    RES VARCHAR2(100) NOT NULL,
    PREG_ID_PREG NUMBER NOT NULL,
    EXAMEN_ID_EXAMEN NUMBER NOT NULL
);
ALTER TABLE RES_USU ADD CONSTRAINT RES_USU_PK PRIMARY KEY (ID_RES_USU);

-- ### 3. CREACIÓN DE LLAVES FORÁNEAS (RELACIONES)
ALTER TABLE MUNICIPIO ADD CONSTRAINT MUNICIPIO_DEPARTAMENTO_FK FOREIGN KEY (DEPARTAMENTO_ID_DEPARTAMENTO) REFERENCES DEPARTAMENTO (ID_DEPARTAMENTO) ON DELETE CASCADE;

ALTER TABLE UBICACION ADD CONSTRAINT UBICACION_ESCUELA_FK FOREIGN KEY (ESCUELA_ID_ESCUELA) REFERENCES ESCUELA (ID_ESCUELA) ON DELETE CASCADE;
ALTER TABLE UBICACION ADD CONSTRAINT UBICACION_CENTRO_FK FOREIGN KEY (CENTRO_ID_CENTRO) REFERENCES CENTRO (ID_CENTRO) ON DELETE CASCADE;

ALTER TABLE REGISTRO ADD CONSTRAINT REGISTRO_MUNICIPIO_FK FOREIGN KEY (MUNICIPIO_ID_MUNICIPIO) REFERENCES MUNICIPIO (ID_MUNICIPIO) ON DELETE CASCADE;
ALTER TABLE REGISTRO ADD CONSTRAINT REGISTRO_UBICACION_FK FOREIGN KEY (UBICACION_ESCUELA_ID, UBICACION_CENTRO_ID) REFERENCES UBICACION (ESCUELA_ID_ESCUELA, CENTRO_ID_CENTRO) ON DELETE CASCADE;

ALTER TABLE EXAMEN ADD CONSTRAINT EXAMEN_REGISTRO_FK FOREIGN KEY (REGISTRO_ID_REGISTRO) REFERENCES REGISTRO (ID_REGISTRO) ON DELETE CASCADE;
ALTER TABLE EXAMEN ADD CONSTRAINT EXAMEN_CORRELATIVO_FK FOREIGN KEY (CORRELATIVO_ID_CORRELATIVO) REFERENCES CORRELATIVO (ID_CORRELATIVO) ON DELETE CASCADE;

ALTER TABLE RES_PRACT_USU ADD CONSTRAINT RES_PRACT_USU_EXAMEN_FK FOREIGN KEY (EXAMEN_ID_EXAMEN) REFERENCES EXAMEN (ID_EXAMEN) ON DELETE CASCADE;
ALTER TABLE RES_PRACT_USU ADD CONSTRAINT RES_PRACT_USU_PREG_PRACT_FK FOREIGN KEY (PREG_PRACT_ID_PREG_PRACT) REFERENCES PREG_PRACT (ID_PREG_PRACT) ON DELETE CASCADE;

ALTER TABLE RES_USU ADD CONSTRAINT RES_USU_EXAMEN_FK FOREIGN KEY (EXAMEN_ID_EXAMEN) REFERENCES EXAMEN (ID_EXAMEN) ON DELETE CASCADE;
ALTER TABLE RES_USU ADD CONSTRAINT RES_USU_PREG_FK FOREIGN KEY (PREG_ID_PREG) REFERENCES PREG (ID_PREG) ON DELETE CASCADE;